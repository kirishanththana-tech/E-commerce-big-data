import { useMemo, useState } from 'react';
import { AlertTriangle, Brain, Download, Gauge, LineChart as LineIcon, Sparkles, TrendingUp } from 'lucide-react';
import { Bar, BarChart, CartesianGrid, Cell, Legend, Line, LineChart, Pie, PieChart, Tooltip, XAxis, YAxis } from 'recharts';
import { Card, CardBody, CardHeader } from '@/components/ui/Card';
import { FilterBar, Filters, defaultFilters } from '@/components/ui/FilterBar';
import { SectionTitle } from '@/components/ui/Feedback';
import { ChartContainer, CHART_COLORS, axisProps, tooltipStyle, formatYAxis, tipCurrency, tipLabel } from '@/components/charts/ChartUtils';
import { churnPrediction, demandForecast, forecastSales, purchasePrediction } from '@/data/predictive';
import { fmtCurrency, fmtNumber } from '@/data/analytics';
import { downloadCSV } from '@/utils/export';

export function PredictiveAnalyticsPage() {
  const [filters, setFilters] = useState<Filters>(defaultFilters);

  const salesForecast = useMemo(() => forecastSales(6), []);
  const churn = useMemo(() => churnPrediction(), []);
  const purchase = useMemo(() => purchasePrediction(), []);
  const demand = useMemo(() => demandForecast(), []);

  const totalChurnRisk = churn.filter((c) => c.name !== 'Safe').reduce((s, c) => s + c.value, 0);
  const safeRate = churn.length ? (churn[0].value / churn.reduce((s, c) => s + c.value, 0)) * 100 : 0;

  return (
    <div className="animate-fade-in">
      <SectionTitle
        title="Predictive Analytics"
        subtitle="Sales forecasting, churn and demand predictions using ML-style models"
        action={
          <button onClick={() => downloadCSV('sales_forecast.csv', salesForecast.map((s) => ({ month: s.month, revenue: s.revenue, type: s.type })))} className="inline-flex items-center gap-2 rounded-lg bg-navy-700 px-4 py-2 text-sm font-medium text-white hover:bg-navy-800">
            <Download size={16} /> Export Forecast
          </button>
        }
      />
      <FilterBar filters={filters} onChange={setFilters} />

      <div className="mb-4 rounded-xl border border-blue-200 bg-blue-50 px-4 py-3 text-sm text-blue-700">
        <Sparkles size={16} className="mr-1.5 inline" />
        Demo predictions: outputs are generated by simple linear-regression and rule-based models running in the browser. Replace with a live ML backend for production use.
      </div>

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <Card><CardBody className="flex items-center justify-between">
          <div><p className="text-xs text-slate-500">Forecast Revenue (next 6 mo)</p><p className="mt-1 text-2xl font-bold text-slate-900">{fmtCurrency(salesForecast.filter((s) => s.type === 'Forecast').reduce((sum, s) => sum + s.revenue, 0))}</p></div>
          <div className="rounded-lg bg-blue-50 p-3 text-blue-600"><TrendingUp size={22} /></div>
        </CardBody></Card>
        <Card><CardBody className="flex items-center justify-between">
          <div><p className="text-xs text-slate-500">Customers at Churn Risk</p><p className="mt-1 text-2xl font-bold text-slate-900">{fmtNumber(totalChurnRisk)}</p></div>
          <div className="rounded-lg bg-rose-50 p-3 text-rose-600"><AlertTriangle size={22} /></div>
        </CardBody></Card>
        <Card><CardBody className="flex items-center justify-between">
          <div><p className="text-xs text-slate-500">Likely to Purchase</p><p className="mt-1 text-2xl font-bold text-slate-900">{fmtNumber(purchase.summary.likely)}</p></div>
          <div className="rounded-lg bg-emerald-50 p-3 text-emerald-600"><Brain size={22} /></div>
        </CardBody></Card>
        <Card><CardBody className="flex items-center justify-between">
          <div><p className="text-xs text-slate-500">Safe Customer Rate</p><p className="mt-1 text-2xl font-bold text-slate-900">{safeRate.toFixed(1)}%</p></div>
          <div className="rounded-lg bg-violet-50 p-3 text-violet-600"><Gauge size={22} /></div>
        </CardBody></Card>
      </div>

      <div className="mt-4 grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Card className="lg:col-span-2">
          <CardHeader title="Future Sales Forecasting" subtitle="Linear regression with seasonal carry-over (actual vs forecast)" icon={LineIcon} />
          <CardBody>
            <ChartContainer height={320}>
              <LineChart data={salesForecast} margin={{ left: -10, right: 10, top: 10, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" vertical={false} />
                <XAxis dataKey="month" {...axisProps} />
                <YAxis tickFormatter={formatYAxis} {...axisProps} />
                <Tooltip contentStyle={tooltipStyle} formatter={tipCurrency(fmtCurrency)} />
                <Legend iconType="circle" wrapperStyle={{ fontSize: 11 }} />
                <Line type="monotone" dataKey="revenue" stroke="#3b82f6" strokeWidth={2.5} dot={{ r: 3 }} name="Revenue" />
              </LineChart>
            </ChartContainer>
          </CardBody>
        </Card>

        <Card>
          <CardHeader title="Customer Churn Prediction" subtitle="Risk distribution across customers" icon={AlertTriangle} />
          <CardBody>
            <ChartContainer height={300}>
              <PieChart>
                <Pie data={churn} dataKey="value" nameKey="name" cx="50%" cy="50%" innerRadius={55} outerRadius={95} paddingAngle={2}>
                  {churn.map((c, i) => <Cell key={i} fill={c.color} />)}
                </Pie>
                <Tooltip contentStyle={tooltipStyle} formatter={tipLabel} />
                <Legend iconType="circle" wrapperStyle={{ fontSize: 11 }} />
              </PieChart>
            </ChartContainer>
          </CardBody>
        </Card>

        <Card>
          <CardHeader title="Purchase Prediction" subtitle="Customers likely to purchase next month" icon={Brain} />
          <CardBody>
            <ChartContainer height={300}>
              <BarChart data={purchase.likely} margin={{ left: -10, right: 10, top: 10, bottom: 40 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" vertical={false} />
                <XAxis dataKey="customerId" {...axisProps} interval={0} angle={-35} textAnchor="end" height={60} />
                <YAxis {...axisProps} />
                <Tooltip contentStyle={tooltipStyle} formatter={(v: unknown) => [`${Number(v)}%`, 'Probability'] as [string, string]} cursor={{ fill: '#f8fafc' }} />
                <Bar dataKey="score" radius={[6, 6, 0, 0]} fill="#22c55e" />
              </BarChart>
            </ChartContainer>
          </CardBody>
        </Card>

        <Card className="lg:col-span-2">
          <CardHeader title="Product Demand Forecasting" subtitle="Next-month units forecast for top 5 products (moving average + trend)" icon={TrendingUp} />
          <CardBody>
            <ChartContainer height={300}>
              <BarChart data={demand} margin={{ left: -10, right: 10, top: 10, bottom: 40 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" vertical={false} />
                <XAxis dataKey="productName" {...axisProps} interval={0} angle={-18} textAnchor="end" height={60} tick={{ ...axisProps.tick, fontSize: 10 }} />
                <YAxis {...axisProps} />
                <Tooltip contentStyle={tooltipStyle} formatter={(v: unknown) => [`${Number(v)} units`, ''] as [string, string]} cursor={{ fill: '#f8fafc' }} />
                <Legend iconType="circle" wrapperStyle={{ fontSize: 11 }} />
                <Bar dataKey="lastMonthUnits" radius={[6, 6, 0, 0]} fill="#94a3b8" name="Last Month" />
                <Bar dataKey="forecast" radius={[6, 6, 0, 0]} fill="#8b5cf6" name="Forecast" />
              </BarChart>
            </ChartContainer>
          </CardBody>
        </Card>
      </div>

      <Card className="mt-4">
        <CardHeader title="High-Probability Purchase Customers" subtitle="Top 10 customers likely to buy again" icon={Brain} />
        <CardBody>
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-slate-200 text-left text-xs uppercase tracking-wide text-slate-500">
                  <th className="px-3 py-2">Customer</th>
                  <th className="px-3 py-2">Last Purchase</th>
                  <th className="px-3 py-2">Frequency</th>
                  <th className="px-3 py-2">Monetary</th>
                  <th className="px-3 py-2 w-1/3">Probability</th>
                </tr>
              </thead>
              <tbody>
                {purchase.likely.map((c) => (
                  <tr key={c.customerId} className="border-b border-slate-100 last:border-0 hover:bg-slate-50">
                    <td className="px-3 py-2.5 font-medium text-slate-800">{c.customerId}</td>
                    <td className="px-3 py-2.5 text-slate-600">{c.lastPurchase}</td>
                    <td className="px-3 py-2.5 text-slate-600">{c.frequency}</td>
                    <td className="px-3 py-2.5 text-slate-600">{fmtCurrency(c.monetary)}</td>
                    <td className="px-3 py-2.5">
                      <div className="flex items-center gap-2">
                        <div className="h-2 flex-1 overflow-hidden rounded-full bg-slate-100">
                          <div className="h-full rounded-full bg-gradient-to-r from-emerald-500 to-emerald-400" style={{ width: `${c.score}%` }} />
                        </div>
                        <span className="text-xs font-semibold text-slate-700">{c.score}%</span>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </CardBody>
      </Card>
    </div>
  );
}
